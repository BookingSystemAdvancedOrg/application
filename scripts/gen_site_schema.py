"""Site document v1: shared artefacts for site-kit (feature B, ADR-B).

    python scripts/gen_site_schema.py            # write
    python scripts/gen_site_schema.py --check    # fail if anything is stale

Writes, from shared/site_schema/v1.json and shared/features/site_builder:

  * shared/site_schema/contrast_vectors.json: accentPair input/output pairs
    computed by the Python port; site-kit's test checks its own accentPair
    gives the same answers (one algorithm, two languages, no drift);
  * ../customer-front-end/packages/site-kit/src/features/site-builder/
    siteSchema.ts (TypeScript types for the document) and
    contrastVectors.json (a copy of the vectors), when that checkout sits
    beside this repo.
"""

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from shared.features import site_builder as sb  # noqa: E402

SCHEMA = ROOT / "shared" / "site_schema" / "v1.json"
VECTORS = ROOT / "shared" / "site_schema" / "contrast_vectors.json"
SITE_KIT = ROOT.parent / "customer-front-end" / "packages" / "site-kit" / "src" / "features" / "site-builder"
INPUTS = ("#350001", "#9a3b26", "#777777", "#888888", "#ff0000", "#ffff00", "#3c8dbc", "#ffffff", "#000000",
          "#c9a227", "#2e7d32", "#7b1fa2", "#ff8800", "#00bcd4")


def vectors():
    return [{"input": c, "mode": m, **sb.accent_pair(c, m)} for c in INPUTS for m in ("light", "dark")]


def _ts_type(schema, indent=0):
    pad = "  " * indent
    if "const" in schema:
        return json.dumps(schema["const"])
    if "enum" in schema:
        return " | ".join(json.dumps(v) for v in schema["enum"])
    if "oneOf" in schema:
        return "\n" + "\n".join(f"{pad}  | {_ts_type(s, indent + 1)}" for s in schema["oneOf"])
    kind = schema.get("type")
    if kind == "string":
        return "string"
    if kind in ("integer", "number"):
        return "number"
    if kind == "boolean":
        return "boolean"
    if kind == "array":
        inner = _ts_type(schema["items"], indent)
        return f"Array<{inner.strip()}>" if "\n" in inner else f"{inner}[]"
    if kind == "object":
        required = set(schema.get("required") or ())
        lines = [f"{pad}  {k}{'' if k in required else '?'}: {_ts_type(v, indent + 1).strip()}"
                 for k, v in (schema.get("properties") or {}).items()]
        return "{\n" + "\n".join(lines) + f"\n{pad}}}"
    raise ValueError(f"unsupported schema node {schema}")


def typescript():
    schema = json.loads(SCHEMA.read_text(encoding="utf-8"))
    page = schema["properties"]["pages"]["items"]
    blocks = page["properties"]["blocks"]["items"]["oneOf"]
    out = ["// Generated by application/scripts/gen_site_schema.py from shared/site_schema/v1.json. Do not edit.", ""]
    names = []
    for block in blocks:
        name = "Block" + block["properties"]["type"]["const"][0].upper() + block["properties"]["type"]["const"][1:]
        names.append(name)
        out.append(f"export type {name} = {_ts_type(block)}")
        out.append("")
    out.append("export type SiteBlock = " + " | ".join(names))
    out.append("")
    page_copy = json.loads(json.dumps(page))
    page_copy["properties"]["blocks"] = {"type": "array", "items": {"type": "string"}}
    page_ts = _ts_type(page_copy).replace("blocks: string[]", "blocks: SiteBlock[]")
    out.append(f"export type SitePage = {page_ts}")
    out.append("")
    doc = json.loads(json.dumps(schema))
    doc["properties"]["pages"] = {"type": "array", "items": {"type": "string"}}
    doc_ts = _ts_type(doc).replace("pages: string[]", "pages: SitePage[]")
    out.append(f"export type SiteDocument = {doc_ts}")
    out.append("")
    out.append("export type SiteBlockType = SiteBlock['type']")
    out.append("")
    return "\n".join(out)


def targets():
    vec = json.dumps(vectors(), indent=2) + "\n"
    files = {VECTORS: vec}
    if SITE_KIT.is_dir():
        files[SITE_KIT / "siteSchema.ts"] = typescript()
        files[SITE_KIT / "contrastVectors.json"] = vec
    return files


def main(argv):
    check = "--check" in argv
    stale = []
    for path, text in targets().items():
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current != text:
            stale.append(path)
            if not check:
                path.write_text(text, encoding="utf-8")
    if check and stale:
        print("stale: " + ", ".join(str(p) for p in stale))
        return 1
    print(("checked " if check else "wrote ") + f"{len(targets())} file(s)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
