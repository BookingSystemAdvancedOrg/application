#!/usr/bin/env python3
"""Generates the contract files of every repo from contracts/booqy.yaml
(infrastructure docs/build/CONTRACTS.md section 1).

    python scripts/gen_contracts.py                       # write all five targets
    python scripts/gen_contracts.py --only application    # one target (repeatable)
    python scripts/gen_contracts.py --check               # write nothing, exit 1 on a diff

Paths are relative to this repo (`application/`); sibling repos are `../<repo>/`.
Needs PyYAML (requirements-dev.txt).
"""

from __future__ import annotations

import argparse
import hashlib
import json
import pprint
import re
import sys
from pathlib import Path

import yaml

APP_ROOT = Path(__file__).resolve().parent.parent
YAML_PATH = APP_ROOT / "contracts" / "booqy.yaml"
HEADER = "generated by application/scripts/gen_contracts.py from application/contracts/booqy.yaml, do not edit"

TARGETS = {
    "application": "shared/contracts.py",
    "console-api": "../booqy-console/api/src/app/contracts.py",
    "admin": "../admin-front-end/src/shared/contracts.ts",
    "console-web": "../booqy-console/web/src/contracts.ts",
    "site-kit": "../customer-front-end/packages/site-kit/src/shared/contracts.ts",
}

# CONTRACTS.md 1.2 rule; its regex as printed rejects Left, Sent and Sold
# (the leading [A-Z] eats the verb's capital), so the capital is a lookahead
# and Sent/Sold join the irregular past tenses the events table uses.
DETAIL_TYPE_RE = re.compile(r"^[A-Z][A-Za-z]+\.(?=[A-Z])[A-Za-z]*(ed|Set|Left|Sent|Sold)(In|Out)?$")
ENUM_RE = re.compile(r"^enum\[([a-z_,]+)\]$")
LIST_RE = re.compile(r"^list\[(.+)\]$")
SCALARS = {"string", "int", "bool", "date", "month", "datetime"}
STORAGE_REGISTRIES = {"siteKit", "admin"}


# --- loading and validation ------------------------------------------------------

class _UniqueKeyLoader(yaml.SafeLoader):
    pass


def _unique_mapping(loader, node, deep=False):
    seen = set()
    for key_node, _ in node.value:
        key = loader.construct_object(key_node, deep=deep)
        if key in seen:
            raise ValueError(f"duplicate key {key!r} (line {key_node.start_mark.line + 1})")
        seen.add(key)
    return loader.construct_mapping(node, deep=deep)


_UniqueKeyLoader.add_constructor(yaml.resolver.BaseResolver.DEFAULT_MAPPING_TAG, _unique_mapping)


def load(raw: bytes) -> dict:
    return yaml.load(raw, Loader=_UniqueKeyLoader)


def _type_ok(t) -> bool:
    if isinstance(t, dict):
        return all(_type_ok(v) for v in t.values())
    if not isinstance(t, str):
        return False
    if t in SCALARS or ENUM_RE.match(t):
        return True
    m = LIST_RE.match(t)
    return bool(m) and _type_ok(m.group(1))


def validate(data: dict) -> list[str]:
    """The self-consistency rules of CONTRACTS.md 1.2; returns the problems."""
    errors = []
    features = data["features"]
    keys = [f["key"] for f in features]
    ids = [f["id"] for f in features]
    for name, values in (("feature key", keys), ("feature id", ids)):
        dupes = sorted({v for v in values if values.count(v) > 1})
        errors += [f"duplicate {name} {d}" for d in dupes]
    if len(keys) != 18 or sum(not f["existing"] for f in features) != 12:
        errors.append("expected 18 features, 12 of them new")
    new_ids = {f["id"] for f in features if not f["existing"]}
    for name, lim in data["limits"].items():
        if lim["feature"] not in keys:
            errors.append(f"limit {name}: unknown feature {lim['feature']}")
        if not lim["min"] <= lim["default"] <= lim["max"]:
            errors.append(f"limit {name}: default outside min..max")
    if not _type_ok(data["events"]["common"]):
        errors.append("events.common: bad field type")
    for source, types in data["events"]["sources"].items():
        if not source.startswith("booqy.") or source[len("booqy."):] not in new_ids:
            errors.append(f"event source {source} is not booqy.<feature-id>")
        for detail_type, fields in types.items():
            if not DETAIL_TYPE_RE.match(detail_type):
                errors.append(f"detail-type {detail_type} breaks the naming rule")
            for field, t in (fields or {}).items():
                if not _type_ok(t):
                    errors.append(f"{detail_type}.{field}: bad type {t!r}")
                if field.rstrip("?") in data["events"]["common"]:
                    errors.append(f"{detail_type}.{field}: repeats a common field")
    for hook, h in data["hooks"].items():
        errors += [f"hook {hook}: unknown target {t}" for t in h["targets"] if t not in new_ids]
    for op, f in data["consoleForwardOps"].items():
        if f["target"] not in new_ids or not op.startswith(f["target"] + "."):
            errors.append(f"console forward op {op}: bad target {f['target']}")
    for host, slots in data["slots"].items():
        for slot, s in slots.items():
            wanted = s["feature"] if isinstance(s["feature"], list) else [s["feature"]]
            errors += [f"{host} slot {slot}: unknown feature {k}" for k in wanted
                       if k not in keys and not (k is None and len(wanted) == 1)]
    if set(data["storage"]) != STORAGE_REGISTRIES:
        errors.append(f"storage: expected the registries {sorted(STORAGE_REGISTRIES)}")
    names = [n for registry in data["storage"].values() for n in registry]
    errors += [f"storage {n}: in more than one registry" for n in sorted({n for n in names if names.count(n) > 1})]
    for registry, entries in data["storage"].items():
        for name, s in entries.items():
            if s["feature"] not in keys:
                errors.append(f"storage {registry}.{name}: unknown feature {s['feature']}")
    site_features = [f["key"] for f in features if f["siteConfig"]]
    if sorted(data["siteConfig"]["tenantFeatures"]) != sorted(site_features):
        errors.append("siteConfig.tenantFeatures differs from the features with siteConfig: true")
    for name in ("tenant.site", "location.waitlist"):
        if not _type_ok(data["siteConfig"][name]):
            errors.append(f"siteConfig.{name}: bad field type")
    return errors


# --- rendering helpers -------------------------------------------------------------

def _py(value) -> str:
    return pprint.pformat(value, width=100, sort_dicts=False)


def _ts(value) -> str:
    return json.dumps(value, indent=2, ensure_ascii=False)


def _sorted(mapping: dict) -> dict:
    return {k: mapping[k] for k in sorted(mapping)}


def _py_type(t) -> str:
    if isinstance(t, dict):
        return "dict"
    if t in ("int", "bool"):
        return t
    if t in SCALARS:
        return "str"
    m = ENUM_RE.match(t)
    if m:
        return "Literal[" + ", ".join(json.dumps(v) for v in m.group(1).split(",")) + "]"
    return f"list[{_py_type(LIST_RE.match(t).group(1))}]"


def _ts_type(t) -> str:
    if isinstance(t, dict):
        return "{ " + "; ".join(f"{_ts_field(k)}: {_ts_type(v)}" for k, v in t.items()) + " }"
    if t == "int":
        return "number"
    if t == "bool":
        return "boolean"
    if t in SCALARS:
        return "string"
    m = ENUM_RE.match(t)
    if m:
        return " | ".join(f"'{v}'" for v in m.group(1).split(","))
    return f"Array<{_ts_type(LIST_RE.match(t).group(1))}>"


def _ts_field(name: str) -> str:
    return name[:-1] + "?" if name.endswith("?") else name


def _union(values) -> str:
    return " | ".join(f"'{v}'" for v in values)


def _split_fields(fields: dict) -> dict:
    fields = fields or {}
    return {
        "required": {k: v for k, v in fields.items() if not k.endswith("?")},
        "optional": {k[:-1]: v for k, v in fields.items() if k.endswith("?")},
    }


def _limits(data: dict) -> dict:
    return _sorted({n: {k: lim[k] for k in ("feature", "min", "max", "default")}
                    for n, lim in data["limits"].items()})


def _slots(data: dict, host: str) -> dict:
    return _sorted({s: {"feature": v["feature"], "ownerOnly": v["ownerOnly"]}
                    for s, v in data["slots"][host].items()})


def _ts_enums(data: dict) -> list[str]:
    return [f"export type {name} = {_union(vals)};" for name, vals in _sorted(data["enums"]).items()]


def _ts_features(data: dict, labels: bool = True) -> list[str]:
    keys = [f["key"] for f in data["features"]]
    out = [f"export const FEATURE_KEYS = {_ts(keys)} as const;",
           "export type FeatureKey = (typeof FEATURE_KEYS)[number];"]
    if labels:
        lab = {f["key"]: {"sv": f["labelSv"], "en": f["labelEn"]} for f in data["features"]}
        out.append(f"export const FEATURE_LABELS: Record<FeatureKey, {{ sv: string; en: string }}> = {_ts(lab)};")
    return out


def _ts_limits(data: dict) -> list[str]:
    limits = _limits(data)
    return [f"export const LIMIT_KEYS = {_ts(list(limits))} as const;",
            "export type LimitKey = (typeof LIMIT_KEYS)[number];",
            "export const LIMITS: Record<LimitKey, { feature: FeatureKey; min: number; max: number; default: number }> = "
            f"{_ts(limits)};"]


def _ts_slots(data: dict, host: str, type_name: str, const: str, nullable: bool) -> list[str]:
    slots = _slots(data, host)
    feature = "FeatureKey | FeatureKey[]" + (" | null" if nullable else "")
    return [f"export type {type_name} = {_union(slots)};",
            f"export const {const}: Record<{type_name}, {{ feature: {feature}; ownerOnly: boolean }}> = {_ts(slots)};"]


# --- targets -------------------------------------------------------------------------

def gen_application(data: dict, digest: str) -> str:
    features = data["features"]
    keys = [f["key"] for f in features]
    sources = _sorted(data["events"]["sources"])
    events = {s: _sorted({dt: _split_fields(f) for dt, f in types.items()}) for s, types in sources.items()}
    out = [f"# {HEADER}", '"""Booqy feature contract (CONTRACTS.md). Regenerate, never edit."""', "",
           "from typing import Literal, NotRequired, TypedDict", "",
           f'CONTRACTS_HASH = "{digest}"', "",
           f"FEATURE_KEYS = {_py(tuple(keys))}",
           f"NEW_FEATURE_KEYS = {_py(tuple(f['key'] for f in features if not f['existing']))}",
           f"FeatureKey = Literal[{', '.join(json.dumps(k) for k in keys)}]",
           f"FEATURE_IDS = {_py({f['key']: f['id'] for f in features})}",
           f"SITE_CONFIG_FEATURES = {_py(tuple(data['siteConfig']['tenantFeatures']))}", "",
           f"LIMITS = {_py(_limits(data))}",
           f"LimitKey = Literal[{', '.join(json.dumps(k) for k in _limits(data))}]", "",
           f'EVENT_BUS = "{data["events"]["bus"]}"',
           f"EVENT_COMMON_FIELDS = {_py(data['events']['common'])}",
           f"EVENT_SOURCES = {_py(tuple(sources))}",
           f"EVENTS = {_py(events)}"]
    common = data["events"]["common"]
    for types in sources.values():
        for dt, fields in _sorted(types).items():
            out += ["", "", f"class {dt.replace('.', '')}Detail(TypedDict):"]
            for name, t in {**common, **(fields or {})}.items():
                py = _py_type(t)
                out.append(f"    {name[:-1]}: NotRequired[{py}]" if name.endswith("?") else f"    {name}: {py}")
    out += ["", "",
            f"HOOKS = {_py(_sorted(data['hooks']))}", "",
            f"CLIENTS = {_py(_sorted(data['clients']))}", ""]
    for name, vals in _sorted(data["enums"]).items():
        out.append(f"{name} = Literal[{', '.join(json.dumps(v) for v in vals)}]")
    return "\n".join(out) + "\n"


def gen_console_api(data: dict, digest: str) -> str:
    return "\n".join([
        f"# {HEADER}", '"""Booqy feature contract (CONTRACTS.md). Regenerate, never edit."""', "",
        f'CONTRACTS_HASH = "{digest}"', "",
        f"FEATURE_KEYS = {_py(tuple(f['key'] for f in data['features']))}",
        f"FEATURE_LABELS_EN = {_py({f['key']: f['labelEn'] for f in data['features']})}",
        f"LIMITS = {_py(_limits(data))}",
        f"CONSOLE_FORWARD_OPS = {_py(_sorted(data['consoleForwardOps']))}",
    ]) + "\n"


def _ts_head(digest: str) -> list[str]:
    return [f"// {HEADER}", "", f"export const CONTRACTS_HASH = '{digest}';", ""]


def gen_admin(data: dict, digest: str) -> str:
    storage = _sorted({name: s["key"] for name, s in data["storage"]["admin"].items()})
    return "\n".join(_ts_head(digest) + _ts_features(data) + [""] + _ts_limits(data) + [""]
                     + _ts_slots(data, "admin", "AdminSlotId", "ADMIN_SLOTS", False) + [""]
                     + [f"export const STORAGE_KEYS = {_ts(storage)} as const;", ""]
                     + _ts_enums(data)) + "\n"


def gen_console_web(data: dict, digest: str) -> str:
    return "\n".join(_ts_head(digest) + _ts_features(data) + [""] + _ts_limits(data) + [""]
                     + _ts_slots(data, "console", "ConsoleSlotId", "CONSOLE_SLOTS", True) + [""]
                     + _ts_enums(data)) + "\n"


def gen_site_kit(data: dict, digest: str) -> str:
    sc = data["siteConfig"]
    storage = data["storage"]["siteKit"]
    return "\n".join(_ts_head(digest) + _ts_features(data, labels=False) + [
        f"export const SITE_CONFIG_FEATURES = {_ts(sc['tenantFeatures'])} as const;",
        "export type SiteFeatureKey = (typeof SITE_CONFIG_FEATURES)[number];", "",
        f"export type SiteBuilderState = {_ts_type(sc['tenant.site'])};",
        f"export type LocationWaitlist = {_ts_type(sc['location.waitlist'])};", "",
    ] + _ts_slots(data, "site", "SiteSlotId", "SITE_SLOTS", False) + [""] + [
        f"export const {name} = '{storage[name]['key']}';" for name in sorted(storage)
    ]) + "\n"


GENERATORS = {
    "application": gen_application,
    "console-api": gen_console_api,
    "admin": gen_admin,
    "console-web": gen_console_web,
    "site-kit": gen_site_kit,
}


def render(raw: bytes) -> dict[str, str]:
    """Target name -> file text for the given YAML bytes."""
    data = load(raw)
    errors = validate(data)
    if errors:
        raise ValueError("contracts/booqy.yaml is not consistent:\n  " + "\n  ".join(errors))
    digest = hashlib.sha256(raw).hexdigest()[:12]
    return {name: gen(data, digest) for name, gen in GENERATORS.items()}


def main(argv=None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--only", action="append", choices=sorted(TARGETS), help="target to generate (repeatable)")
    parser.add_argument("--check", action="store_true", help="write nothing; exit 1 listing files that differ")
    args = parser.parse_args(argv)
    texts = render(YAML_PATH.read_bytes())
    stale = []
    for name in args.only or TARGETS:
        path = (APP_ROOT / TARGETS[name]).resolve()
        current = path.read_text(encoding="utf-8") if path.exists() else None
        if current == texts[name]:
            continue
        if args.check:
            stale.append(f"{name}: {path} {'missing' if current is None else 'differs'}")
        else:
            path.write_text(texts[name], encoding="utf-8")
            print(f"wrote {path}")
    if stale:
        print("contract files out of date (run scripts/gen_contracts.py):\n  " + "\n  ".join(stale), file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
